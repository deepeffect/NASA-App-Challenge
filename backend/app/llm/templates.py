"""Kural tabanlı metin şablonları — LLM olmadan (veya LLM başarısız olunca) cevap üretir.

Üç kullanım:
  1) Mock modda (LLM_PROVIDER=mock) "modelin" cevabı
  2) Explain/briefing'de LLM şemaya uymazsa veya erişilemezse yedek (generated_by=template_fallback)
  3) Sohbette LLM çevrim dışıyken kısa özet
Sayıların tamamı bağlamdan/tool sonuçlarından gelir (hesap yapılmaz).
Kullanıcıya görünen tüm metinler İngilizcedir. `lang` parametreleri uyumluluk için durur (tek değer: "en").
"""

from typing import Any

from app.analysis.text import fmt, unit_label

STATUS = {"green": "normal (green)", "yellow": "attention (yellow)", "red": "critical (red)", "unknown": "no data"}
SEVERITY = {"info": "info", "warning": "warning", "critical": "critical"}
SYSTEMS = {"cardiovascular": "Cardiovascular", "musculoskeletal": "Musculoskeletal", "immune": "Immune",
           "behavioral": "Behavioral health", "sleep": "Sleep", "radiation": "Radiation"}
SYSTEM_ACTIONS = {
    "sleep": "Review the sleep schedule and sleep environment (light, noise, temperature).",
    "behavioral": "Discuss workload and rest balance with the CMO; activate the support plan if needed.",
    "cardiovascular": "Repeat the measurement at rest; review exercise intensity and fluid intake.",
    "musculoskeletal": "Check adherence to the exercise protocol.",
    "immune": "Re-measure body temperature during the day and log symptoms.",
    "radiation": "Check dose records; review shelter procedures during high-dose periods.",
}
T = {
    "cmo": "Review this with the crew medical officer (CMO).",
    "monitor": "Keep monitoring this metric over the coming days.",
    "placeholder": "Thresholds are placeholders, not yet validated against NASA-STD-3001.",
    "template": "This text was generated by a rule-based template without the AI model.",
    "mock": "(Mock mode: this answer comes from a template; no real model is connected.)",
    "offline": "(Assistant offline: showing a rule-based summary. Alerts keep working.)",
    "no_factor": "No clear concurrent change found; the change is limited to one metric.",
    "concurrent": "{name} also changed unfavourably in the same period ({sev}).",
    "note": "Check-in note: “{note}”",
    "continue": "Continue the current routine.",
    "checkin": "Complete the daily check-in.",
    "normal_sys": "{name}: within personal normal range",
}


def _val(v: Any, unit: str, decimals: int) -> str:
    u = unit_label(unit)
    return f"{fmt(v, decimals)}{u}" if u.startswith("/") else f"{fmt(v, decimals)} {u}"


# =============================================================================
# Uyarı açıklaması (AlertExplanation)
# =============================================================================
def alert_explanation(ctx: dict[str, Any], lang: str = "en") -> dict[str, Any]:
    """ctx: services/llm_service.build_explain_context() çıktısı."""
    ev = ctx["event"]
    metrics = ctx.get("metrics", {})
    parts = []
    for c in ev["contributors"]:
        info = metrics.get(c["metric"], {})
        name = info.get("display_name", c["metric"])
        unit, dec = info.get("unit", ""), info.get("decimals", 1)
        if c.get("value") is not None and c.get("baseline") is not None:
            parts.append(f"{name}: {_val(c['value'], unit, dec)} vs personal normal {_val(c['baseline'], unit, dec)}")
        else:
            parts.append(name)
    sev = SEVERITY[ev["severity"]]
    summary = f"{SYSTEMS[ev['system']]} alert ({sev}) since {ev['window']['start']}: " + "; ".join(parts) + "."

    factors = []
    for r in ctx.get("related_active_events", [])[:3]:
        info = metrics.get(r["metric"], {})
        name = info.get("display_name", r["metric"])
        factors.append(T["concurrent"].format(name=name, sev=SEVERITY[r["severity"]]))
    for note in ctx.get("recent_checkin_notes", [])[:2]:
        factors.append(T["note"].format(note=note))
    if not factors:
        factors.append(T["no_factor"])

    actions = [SYSTEM_ACTIONS[ev["system"]]]
    if ev["severity"] in ("warning", "critical"):
        actions.append(T["cmo"])
    actions.append(T["monitor"])

    sources = [f"event:{ev['event_id']}"] + [f"metric:{c['metric']}" for c in ev["contributors"]]
    sources += [f"doc:{d['file']}#{d.get('section') or ''}" for d in ctx.get("docs", [])]
    unverified = any(m.get("threshold_verified") is False for m in metrics.values())
    uncertainty = " ".join(x for x in (T["placeholder"] if unverified else "", T["template"]) if x)
    return {"summary": summary, "likely_factors": factors, "recommended_actions": actions,
            "escalate_to_ground": ev["severity"] == "critical", "sources": sources, "uncertainty": uncertainty}


# =============================================================================
# Günlük brifing (DailyBriefing)
# =============================================================================
def daily_briefing(ctx: dict[str, Any], lang: str = "en") -> dict[str, Any]:
    """ctx: services/llm_service.build_briefing_context() çıktısı."""
    ov = ctx["overall"]
    alerts = ctx.get("active_alerts", [])
    infos = ctx.get("info_alerts", [])
    score = fmt(ov.get("score"), 0) if ov.get("score") is not None else "—"
    summary = f"Mission day {ctx.get('mission_day')}: overall status {STATUS[ov['status']]}, score {score}/100."
    summary += f" {len(alerts)} active alert(s)." if alerts else " No active alerts."
    highlights = [T["normal_sys"].format(name=SYSTEMS[s["system"]])
                  for s in ctx.get("systems", []) if s["status"] == "green"][:3]
    concerns = [f"{a['title']} ({SEVERITY[a['severity']]})" for a in alerts][:5]
    flagged_systems = list(dict.fromkeys(a["system"] for a in alerts))
    actions = [SYSTEM_ACTIONS[s] for s in flagged_systems[:2]]
    if alerts:
        actions.append(T["cmo"])
    else:
        actions = [T["continue"], T["checkin"]]
    return {
        "summary": summary, "highlights": highlights, "concerns": concerns, "recommended_actions": actions,
        "info_notes": [i["title"] for i in infos][:5],
        "escalate_to_ground": any(a["severity"] == "critical" for a in alerts),
        "sources": [f"event:{a['event_id']}" for a in alerts + infos],
        "uncertainty": f"{T['placeholder']} {T['template']}",
    }


# =============================================================================
# Sohbet: tool sonuçlarından cevap (mock + çevrim dışı yedek)
# =============================================================================
def _tool_text(name: str, d: dict[str, Any]) -> str:
    if "error" in d and len(d) <= 2:
        return "Could not fetch data: " + str(d["error"])
    if name == "get_health_summary":
        ov = d["overall"]
        score = fmt(ov.get("score"), 0) if ov.get("score") is not None else "—"
        s = f"Your overall status is {STATUS[ov['status']]}, score {score}/100."
        alerts = d.get("active_alerts", [])
        if alerts:
            titles = "; ".join(a["title"] for a in alerts[:3])
            s += f" There are {len(alerts)} active alerts: {titles}."
            for m in d.get("out_of_normal_metrics", [])[:3]:
                if m.get("rolling_7d_mean") is not None and m.get("personal_baseline") is not None:
                    s += (f" {m['display_name']}: 7-day mean {_val(m['rolling_7d_mean'], m['unit'], 1)}, "
                          f"personal normal {_val(m['personal_baseline'], m['unit'], 1)}.")
        else:
            s += " No active alerts; your metrics are within your personal normal range."
        return s
    if name == "get_metric":
        lt, b = d.get("latest", {}), d.get("personal_baseline") or {}
        s = f"{d['display_name']}: latest {_val(lt.get('value'), d['unit'], 1)} ({lt.get('date')})"
        if b.get("mean") is not None:
            s += f", personal normal {_val(b['mean'], d['unit'], 1)}"
        s += "."
        if d.get("active_alerts"):
            s += " Related alert: " + d["active_alerts"][0]["title"] + "."
        return s
    if name == "get_alerts":
        if not d.get("alerts"):
            return "No active alerts."
        items = "; ".join(f"{a['title']} ({SEVERITY[a['severity']]})" for a in d["alerts"][:4])
        return "Active alerts: " + items + "."
    if name == "get_radiation_dose":
        dl, cu = d.get("daily_latest", {}), d.get("cumulative", {})
        s = (f"Daily dose {fmt(dl.get('value'), 2)} mSv, last 7 days {fmt(d.get('last_7_days_total'), 1)} mSv, "
             f"cumulative {fmt(cu.get('value'), 1)} mSv.")
        return s + " " + T["placeholder"]
    if name == "get_checkins":
        cks = d.get("checkins", [])
        if not cks:
            return "No recent check-ins."
        c = cks[0]
        return f"Latest check-in ({c['date']}): mood {c['mood']}/5, stress {c['stress']}/5, sleep quality {c['sleep_quality']}/5."
    if name == "search_docs":
        res = d.get("results", [])
        if not res:
            return "No matching onboard document found."
        refs = "; ".join(f"{r['file']}" + (f" § {r['section']}" if r.get("section") else "") for r in res[:3])
        return "Relevant documents: " + refs + "."
    return ""


def chat_answer(tool_results: list[tuple[str, dict[str, Any]]], lang: str = "en", mode: str = "mock") -> str:
    """mode: 'mock' | 'offline' (dipnot farklı)."""
    parts = [t for t in (_tool_text(n, d) for n, d in tool_results) if t]
    if not parts:
        parts = ["I need to look at your health data to help."]
    if any(n == "get_health_summary" and d.get("active_alerts") for n, d in tool_results):
        parts.append(T["cmo"])
    return " ".join(parts) + "\n\n" + T[mode]
