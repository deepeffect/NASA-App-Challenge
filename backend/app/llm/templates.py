# Uyarı açıklaması (AlertExplanation)
# =============================================================================
def alert_explanation(ctx: dict[str, Any], lang: str = "tr") -> dict[str, Any]:
    """ctx: services/llm_service.build_explain_context() çıktısı."""
    L = _l(lang)
    ev = ctx["event"]
    metrics = ctx.get("metrics", {})
    parts = []
    for c in ev["contributors"]:
        info = metrics.get(c["metric"], {})
        name = info.get("display_name_en" if L == "en" else "display_name", c["metric"])
        unit, dec = info.get("unit", ""), info.get("decimals", 1)
        if c.get("value") is not None and c.get("baseline") is not None:
            if L == "en":
                parts.append(f"{name}: {_val(c['value'], unit, dec)} vs personal normal {_val(c['baseline'], unit, dec)}")
            else:
                parts.append(f"{name}: {_val(c['value'], unit, dec)} (kişisel normal {_val(c['baseline'], unit, dec)})")
        else:
            parts.append(name)
    sev = SEVERITY[L][ev["severity"]]
    if L == "en":
        summary = f"{SYSTEMS['en'][ev['system']]} alert ({sev}) since {ev['window']['start']}: " + "; ".join(parts) + "."
    else:
        since = ".".join(reversed(ev["window"]["start"].split("-")))  # 2026-10-17 → 17.10.2026
        summary = f"{ev['title']} ({sev}, {since} tarihinden beri). " + (ev.get("description") or "; ".join(parts))

    factors = []
    for r in ctx.get("related_active_events", [])[:3]:
        info = metrics.get(r["metric"], {})
        name = info.get("display_name_en" if L == "en" else "display_name", r["metric"])
        factors.append(T[L]["concurrent"].format(name=name, sev=SEVERITY[L][r["severity"]]))
    for note in ctx.get("recent_checkin_notes", [])[:2]:
        factors.append(T[L]["note"].format(note=note))
    if not factors:
        factors.append(T[L]["no_factor"])

    actions = [SYSTEM_ACTIONS[L][ev["system"]]]
    if ev["severity"] in ("warning", "critical"):
        actions.append(T[L]["cmo"])
    actions.append(T[L]["monitor"])

    sources = [f"event:{ev['event_id']}"] + [f"metric:{c['metric']}" for c in ev["contributors"]]
    sources += [f"doc:{d['file']}#{d.get('section') or ''}" for d in ctx.get("docs", [])]
    unverified = any(m.get("threshold_verified") is False for m in metrics.values())
    uncertainty = " ".join(x for x in (T[L]["placeholder"] if unverified else "", T[L]["template"]) if x)
    return {"summary": summary, "likely_factors": factors, "recommended_actions": actions,
            "escalate_to_ground": ev["severity"] == "critical", "sources": sources, "uncertainty": uncertainty}


# =============================================================================
# Günlük brifing (DailyBriefing)
# =============================================================================
def daily_briefing(ctx: dict[str, Any], lang: str = "tr") -> dict[str, Any]:
    """ctx: services/llm_service.build_briefing_context() çıktısı."""
    L = _l(lang)
    ov = ctx["overall"]
    alerts = ctx.get("active_alerts", [])
    infos = ctx.get("info_alerts", [])
    score = fmt(ov.get("score"), 0) if ov.get("score") is not None else "—"
    if L == "en":
        summary = f"Mission day {ctx.get('mission_day')}: overall status {STATUS['en'][ov['status']]}, score {score}/100."
        summary += f" {len(alerts)} active alert(s)." if alerts else " No active alerts."
    else:
        summary = f"Görev günü {ctx.get('mission_day')}: genel durum {STATUS['tr'][ov['status']]}, skor {score}/100."
        summary += f" {len(alerts)} aktif uyarı var." if alerts else " Aktif uyarı yok."
    highlights = [T[L]["normal_sys"].format(name=SYSTEMS[L][s["system"]])
                  for s in ctx.get("systems", []) if s["status"] == "green"][:3]
    concerns = [f"{a['title']} ({SEVERITY[L][a['severity']]})" for a in alerts][:5]
    flagged_systems = list(dict.fromkeys(a["system"] for a in alerts))
    actions = [SYSTEM_ACTIONS[L][s] for s in flagged_systems[:2]]
    if alerts:
        actions.append(T[L]["cmo"])
    else:
        actions = [T[L]["continue"], T[L]["checkin"]]
    return {
        "summary": summary, "highlights": highlights, "concerns": concerns, "recommended_actions": actions,
        "info_notes": [i["title"] for i in infos][:5],
        "escalate_to_ground": any(a["severity"] == "critical" for a in alerts),
        "sources": [f"event:{a['event_id']}" for a in alerts + infos],
        "uncertainty": f"{T[L]['placeholder']} {T[L]['template']}",
    }


