# Sohbet: tool sonuçlarından cevap (mock + çevrim dışı yedek)
# =============================================================================
def _tool_text(name: str, d: dict[str, Any], L: str) -> str:
    if "error" in d and len(d) <= 2:
        return ("Veri alınamadı: " if L == "tr" else "Could not fetch data: ") + str(d["error"])
    if name == "get_health_summary":
        ov = d["overall"]
        score = fmt(ov.get("score"), 0) if ov.get("score") is not None else "—"
        if L == "en":
            s = f"Your overall status is {STATUS['en'][ov['status']]}, score {score}/100."
        else:
            s = f"Genel durumun {STATUS['tr'][ov['status']]}, skor {score}/100."
        alerts = d.get("active_alerts", [])
        if alerts:
            titles = "; ".join(a["title"] for a in alerts[:3])
            s += (f" There are {len(alerts)} active alerts: {titles}." if L == "en"
                  else f" Dikkat gerektiren {len(alerts)} uyarı var: {titles}.")
            for m in d.get("out_of_normal_metrics", [])[:3]:
                if m.get("rolling_7d_mean") is not None and m.get("personal_baseline") is not None:
                    s += (f" {m['display_name']}: 7-day mean {_val(m['rolling_7d_mean'], m['unit'], 1)}, "
                          f"personal normal {_val(m['personal_baseline'], m['unit'], 1)}." if L == "en" else
                          f" {m['display_name']}: 7 günlük ortalama {_val(m['rolling_7d_mean'], m['unit'], 1)}, "
                          f"kişisel normal {_val(m['personal_baseline'], m['unit'], 1)}.")
        else:
            s += " No active alerts; your metrics are within your personal normal range." if L == "en" else \
                " Aktif uyarı yok; ölçümlerin kişisel normal aralığında."
        return s
    if name == "get_metric":
        lt, b = d.get("latest", {}), d.get("personal_baseline") or {}
        s = (f"{d['display_name']}: latest {_val(lt.get('value'), d['unit'], 1)} ({lt.get('date')})" if L == "en"
             else f"{d['display_name']}: son değer {_val(lt.get('value'), d['unit'], 1)} ({lt.get('date')})")
        if b.get("mean") is not None:
            s += (f", personal normal {_val(b['mean'], d['unit'], 1)}" if L == "en"
                  else f", kişisel normal {_val(b['mean'], d['unit'], 1)}")
        s += "."
        if d.get("active_alerts"):
            s += (" Related alert: " if L == "en" else " İlgili uyarı: ") + d["active_alerts"][0]["title"] + "."
        return s
    if name == "get_alerts":
        if not d.get("alerts"):
            return "No active alerts." if L == "en" else "Aktif uyarı yok."
        items = "; ".join(f"{a['title']} ({SEVERITY[L][a['severity']]})" for a in d["alerts"][:4])
        return ("Active alerts: " if L == "en" else "Aktif uyarılar: ") + items + "."
    if name == "get_radiation_dose":
        dl, cu = d.get("daily_latest", {}), d.get("cumulative", {})
        if L == "en":
            s = f"Daily dose {fmt(dl.get('value'), 2)} mSv, last 7 days {fmt(d.get('last_7_days_total'), 1)} mSv, cumulative {fmt(cu.get('value'), 1)} mSv."
        else:
            s = f"Günlük doz {fmt(dl.get('value'), 2)} mSv, son 7 gün toplamı {fmt(d.get('last_7_days_total'), 1)} mSv, kümülatif {fmt(cu.get('value'), 1)} mSv."
        return s + " " + T[L]["placeholder"]
    if name == "get_checkins":
        cks = d.get("checkins", [])
        if not cks:
            return "No recent check-ins." if L == "en" else "Son günlerde check-in yok."
        c = cks[0]
        return (f"Latest check-in ({c['date']}): mood {c['mood']}/5, stress {c['stress']}/5, sleep quality {c['sleep_quality']}/5."
                if L == "en" else
                f"Son check-in ({c['date']}): ruh hali {c['mood']}/5, stres {c['stress']}/5, uyku kalitesi {c['sleep_quality']}/5.")
    if name == "search_docs":
        res = d.get("results", [])
        if not res:
            return "No matching onboard document found." if L == "en" else "Gemideki belgelerde ilgili kaynak bulunamadı."
        refs = "; ".join(f"{r['file']}" + (f" § {r['section']}" if r.get("section") else "") for r in res[:3])
        return ("Relevant documents: " if L == "en" else "İlgili belgeler: ") + refs + "."
    return ""


def chat_answer(tool_results: list[tuple[str, dict[str, Any]]], lang: str = "tr", mode: str = "mock") -> str:
    """mode: 'mock' | 'offline' (dipnot farklı)."""
    L = _l(lang)
    parts = [t for t in (_tool_text(n, d, L) for n, d in tool_results) if t]
    if not parts:
        parts = ["Size yardımcı olabilmem için sağlık verilerinize bakmam gerekiyor." if L == "tr"
                 else "I need to look at your health data to help."]
    if any(n == "get_health_summary" and d.get("active_alerts") for n, d in tool_results):
        parts.append(T[L]["cmo"])
    return " ".join(parts) + "\n\n" + T[L][mode]
